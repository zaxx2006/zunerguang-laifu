import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";
import { randomBytes } from "node:crypto";
import { execFileSync } from "node:child_process";
import config from "@payload-config";
import { getPayload } from "payload";
import { sitePageEnvelopeSchema } from "@/contracts/cms-site-page";

const cms = "http://127.0.0.1:5158";
const website = "http://localhost:3001";
assert.ok(["localhost", "127.0.0.1"].includes(new URL(process.env.PAYLOAD_PUBLIC_SERVER_URL || cms).hostname), "只允许本地验收");
const payload = await getPayload({ config });
const secret = process.env.LAIFU_PREVIEW_SECRET;
assert.ok(secret && secret.length >= 32, "缺少预览连接配置");
const pages = await payload.find({ collection: "site-pages", pagination: false, depth: 0, overrideAccess: true });
const seeds = JSON.parse(fs.readFileSync(new URL("../../seed-data/site-pages.json", import.meta.url), "utf8")) as { route: string }[];
assert.deepEqual(pages.docs.map(page => page.route).sort(), seeds.map(page => page.route).sort());
for (const page of pages.docs) {
  const response = await fetch(`${cms}/api/public/v1/laifu/site-pages?route=${encodeURIComponent(page.route)}`);
  assert.equal(response.status, 200, page.route);
  assert.equal(sitePageEnvelopeSchema.parse(await response.json()).data.presentation.route, page.route);
}
console.log("27 个 CMS 页面接口及完整内容合同通过");
const admin = (await payload.find({ collection: "users", where: { roles: { contains: "admin" } }, limit: 1, overrideAccess: true })).docs[0];
assert.ok(admin, "缺少本地管理员");
const page = pages.docs.find(page => page.route === "/services/co-parenting/")!;
const previewTitle = `${page.title}（草稿验收）`;
let qaUser: number | undefined;
let requestID: number | undefined;
try {
  await payload.update({ collection: "site-pages", id: page.id, draft: true, overrideAccess: true, user: admin, data: { title: previewTitle } });
  const draft = await fetch(`${cms}/api/preview/v1/laifu/page?id=${page.id}`, { headers: { Authorization: `Bearer ${secret}` } });
  assert.equal(draft.status, 200);
  assert.equal(sitePageEnvelopeSchema.parse(await draft.json()).data.presentation.title, previewTitle);
  const published = await fetch(`${cms}/api/public/v1/laifu/site-pages?route=${encodeURIComponent(page.route)}`);
  assert.equal(sitePageEnvelopeSchema.parse(await published.json()).data.presentation.title, page.title);
  const previewURL = new URL("/api/cms/preview/", website);
  for (const [key, value] of Object.entries({ collection: "site-pages", id: String(page.id), route: page.route, secret })) previewURL.searchParams.set(key, value);
  const entry = await fetch(previewURL, { redirect: "manual" });
  assert.equal(entry.status, 307);
  const cookie = entry.headers.getSetCookie().map(value => value.split(";")[0]).join("; ");
  const rendered = await fetch(`${website}${page.route}`, { headers: { Cookie: cookie } });
  const html = await rendered.text();
  assert.equal(rendered.status, 200);
  assert.ok(html.includes(previewTitle), "前台未显示草稿");
  assert.match(html, /name="robots" content="noindex, nofollow"/, "草稿缺少 noindex");
  await payload.update({ collection: "site-pages", id: page.id, draft: false, overrideAccess: true, user: admin, data: { title: page.title, _status: "published" } });
  const event = await payload.find({ collection: "publish-events", where: { and: [{ resource: { equals: "site-pages" } }, { documentId: { equals: String(page.id) } }] }, sort: "-createdAt", limit: 1, overrideAccess: true });
  assert.equal(event.docs[0]?.deliveryStatus, "succeeded", "发布后前台缓存更新未成功");
  console.log("草稿隔离、前台预览、noindex 和发布缓存更新通过");
  const submission = { name: "开发验收临时数据", phone: "19900000000", wechat: "", consultationType: "深度咨询", concern: "仅用于本地开发验收，完成后删除此条测试申请。", consent: true, website: "" };
  const submit = (data: unknown) => fetch(`${website}/api/consultations`, { method: "POST", headers: { Origin: website, "Content-Type": "application/json" }, body: JSON.stringify(data) });
  assert.equal((await submit({ ...submission, consent: false })).status, 400);
  assert.equal((await fetch(`${cms}/api/consultations`, { method: "POST", body: JSON.stringify(submission) })).status, 401);
  assert.equal((await submit(submission)).status, 201);
  const stored = await payload.find({ collection: "consultation-requests", where: { name: { equals: submission.name } }, limit: 1, overrideAccess: true });
  requestID = stored.docs[0]?.id;
  assert.ok(requestID);
  assert.equal(stored.docs[0].concern, submission.concern);
  assert.equal(stored.docs[0].status, "new");
  assert.equal((await submit(submission)).status, 429);
  assert.equal((await fetch(`${cms}/api/consultation-requests/${requestID}`)).status, 403);
  console.log("预约非法输入拒绝、真实落库、防重复提交与隐私访问检查通过");
  const email = `site-qa-${Date.now()}@laifu.local`;
  const password = randomBytes(24).toString("base64url");
  const user = await payload.create({ collection: "users", overrideAccess: true, data: { email, password, name: "站点验收临时账号", roles: ["admin"] } });
  qaUser = user.id;
  const binary = path.join(process.env.APPDATA!, "npm/node_modules/agent-browser/bin/agent-browser-win32-x64.exe");
  const browser = (...args: string[]) => execFileSync(binary, ["--session", "laifu-site-cms", ...args], { encoding: "utf8", timeout: 60000, maxBuffer: 2 * 1024 * 1024 }).trim();
  browser("eval", `fetch('/api/users/login',{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify(${JSON.stringify({ email, password })})}).then(r=>({status:r.status}))`);
  browser("open", `${cms}/admin/collections/site-pages/${page.id}`);
  browser("wait", "--text", "首屏标题");
  const snapshot = browser("snapshot", "-i", "-d", "4");
  assert.ok(snapshot.includes("首屏标题"), "CMS 编辑页未显示标题字段");
  fs.writeFileSync(new URL("../../../artifacts/site-cms-editor-snapshot.txt", import.meta.url), snapshot);
  browser("screenshot", path.resolve("../artifacts/site-cms-editor.png"));
  console.log("CMS 页面编辑界面可打开，截图已保存");
} finally {
  await payload.update({ collection: "site-pages", id: page.id, draft: false, overrideAccess: true, user: admin, data: { title: page.title, _status: "published" } });
  if (requestID) await payload.delete({ collection: "consultation-requests", id: requestID, overrideAccess: true });
  if (qaUser) await payload.delete({ collection: "users", id: qaUser, overrideAccess: true });
  await payload.destroy();
}
console.log("验收完成；临时数据已清理");
process.exit(0);
